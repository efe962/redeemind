export async function checkLocales(
  root = resolve(import.meta.dirname, '..'),
): Promise<LocaleCheckResult> {
  const localesDir = join(root, '_locales');
  const allowlist = JSON.parse(
    await readFile(join(root, 'scripts', 'locale-allowlist.json'), 'utf8'),
  ) as { globalKeys?: string[]; values?: string[]; languageKeys?: string[] };
  const allowedKeys = new Set(allowlist.globalKeys ?? []);
  const allowedValues = new Set(allowlist.values ?? []);
  const allowedLanguageKeys = new Set(allowlist.languageKeys ?? []);
  const locales = readdirSync(localesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const errors: string[] = [];
  const catalogs = new Map<string, Record<string, Message>>();
  for (const locale of locales) {
    try {
      catalogs.set(
        locale,
        JSON.parse(await readFile(join(localesDir, locale, 'messages.json'), 'utf8')),
      );
    } catch (error) {
      errors.push(`${locale}: invalid JSON (${String(error)})`);
    }
  }
  const source = catalogs.get('en');
  if (!source) return { locales, errors: [...errors, 'en: source locale is missing'] };
  const sourceKeys = Object.keys(source).sort();
  const languageKeys = [
    'languageEnglish',
    'languageGerman',
    'languageSpanish',
    'languageFrench',
    'languagePortugueseBrazil',
    'languagePortuguesePortugal',
    'languageItalian',
    'languageDutch',
    'languagePolish',
    'languageRussian',
    'languageTurkish',
    'languageJapanese',
    'languageKorean',
    'languageChineseSimplified',
    'languageChineseTraditional',
    'languageHindi',
    'languageArabic',
    'languageIndonesian',
    'languageUkrainian',
    'languageSwedish',
  ];
  const placeholders = (catalog: Record<string, { placeholders?: unknown }>, key: string) =>
    JSON.stringify(catalog[key]?.placeholders ?? null);
  for (const locale of locales) {
    const catalog = catalogs.get(locale);
    if (!catalog) continue;
    const keys = Object.keys(catalog).sort();
    if (JSON.stringify(keys) !== JSON.stringify(sourceKeys))
      errors.push(`${locale}: keys differ from en`);
    for (const key of sourceKeys) {
      if (!catalog[key]?.message?.trim()) errors.push(`${locale}.${key}: empty message`);
      if (placeholders(source, key) !== placeholders(catalog, key))
        errors.push(`${locale}.${key}: placeholders differ from en`);
      if (
        locale !== 'en' &&
        !allowedKeys.has(key) &&
        !allowedValues.has(catalog[key]?.message ?? '') &&
        !allowedLanguageKeys.has(`${locale}.${key}`) &&
        catalog[key]?.message === source[key]?.message
      ) {
        errors.push(`${locale}.${key}: untranslated (same as en: ${source[key]?.message})`);
      }
      if (locale !== 'en' && !allowedLanguageKeys.has(`${locale}.${key}`)) {
        const words = new Set([
          ...(languageWords[locale] ?? englishWords),
          ...(locale === 'it' || locale === 'nl' || locale === 'pt_BR' || locale === 'pt_PT'
            ? englishWords
            : []),
        ]);
        const forbidden = englishWords.filter(
          (word) =>
            !words.has(word) && new RegExp(`\\b${word}\\b`, 'i').test(catalog[key]?.message ?? ''),
        );
        if (forbidden.length)
          errors.push(
            `${locale}.${key}: English words [${forbidden.join(', ')}] in "${catalog[key]?.message}"`,
          );
        if (locale !== 'de') {
          const german = germanWords.filter((word) =>
            new RegExp(`\\b${word}\\b`, 'i').test(catalog[key]?.message ?? ''),
          );
          if (german.length)
            errors.push(
              `${locale}.${key}: German words [${german.join(', ')}] in "${catalog[key]?.message}"`,
            );
        }
        if (
          /\s*\((en|de|es|fr|pt|it|nl|pl|ru|tr|ja|ko|zh|hi|ar|id|uk|sv)\)\s*$/i.test(
            catalog[key]?.message ?? '',
          )
        )
          errors.push(`${locale}.${key}: language suffix in "${catalog[key]?.message}"`);
      }
      if (locale !== 'en' && languageKeys.includes(key)) {
        const expected = languageNames[locale]?.[languageKeys.indexOf(key)];
        if (expected && catalog[key]?.message !== expected)
          errors.push(`${locale}.${key}: expected "${expected}", got "${catalog[key]?.message}"`);
      }
    }
    if (locale !== 'en') {
      const duplicateKeys = new Map<string, string[]>();
      for (const key of sourceKeys) {
        const message = catalog[key]?.message;
        if (!message || allowedValues.has(message)) continue;
        duplicateKeys.set(message, [...(duplicateKeys.get(message) ?? []), key]);
      }
      for (const [message, keysWithMessage] of duplicateKeys) {
        if (keysWithMessage.length > 1) {
          errors.push(
            `${locale}: duplicate message "${message}" for keys ${keysWithMessage.join(', ')}`,
          );
        }
      }
    }
  }
  return { locales, errors };
}

if (process.argv[1]?.endsWith('check-locales.ts')) {
  const result = await checkLocales();
  if (result.errors.length) {
    console.error(result.errors.join('\n'));
    process.exitCode = 1;
  } else {
    console.log(`Validated ${result.locales.length} locale catalogs.`);
  }
}
